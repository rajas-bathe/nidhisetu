/**
 * Provider-neutral object storage surface.
 *
 * Document bodies never touch the database and are never served statically:
 * upload/download flows call the adapter and authorization happens in the
 * document service using PostgreSQL records, so swapping local file storage
 * for an S3-compatible bucket does not change any permission behaviour.
 */
export interface StoredObjectResult {
  /** Generated storage key (opaque token; never a client-controlled path). */
  key: string;
}

/**
 * Storage adapters behave like durable stores. Key generation and validation
 * live in keys.ts so no adapter trusts a client-controlled path.
 */
export interface StorageAdapter {
  readonly name: "local" | "s3";
  /**
   * Saves bytes under `key` (generated by buildObjectKey). Fails if an object
   * already exists under the same key (write-once, like web storage).
   */
  put(object: Buffer, key: string): Promise<StoredObjectResult>;
  /** Resolves the exact bytes previously stored under `key`. */
  get(key: string): Promise<Buffer>;
  /** Removes the object. Missing objects must not throw. */
  delete(key: string): Promise<void>;
}

/** Thrown for storage-configuration problems; surfacing happens at boot/use. */
export class StorageConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "StorageConfigError";
  }
}
